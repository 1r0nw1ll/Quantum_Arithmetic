def main():
    """CLI interface for Grok-Code"""
    import argparse

    parser = argparse.ArgumentParser(description="Grok-Code v4.0 - QA Code Analysis & Generation")
    subparsers = parser.add_subparsers(dest="command", help="Available commands")

    # Analyze command
    analyze_parser = subparsers.add_parser("analyze", help="Analyze Python file for QA compliance")
    analyze_parser.add_argument("filepath", help="Python file to analyze")

    # Generate command
    generate_parser = subparsers.add_parser("generate", help="Generate code from theorem description")
    generate_parser.add_argument("theorem", help="Theorem name")
    generate_parser.add_argument("description", help="Theorem description")

    # Test command
    test_parser = subparsers.add_parser("testgen", help="Generate test template for file")
    test_parser.add_argument("filepath", help="Python file to generate tests for")

    # Optimize command
    optimize_parser = subparsers.add_parser("optimize", help="Suggest code optimizations")
    optimize_parser.add_argument("filepath", help="Python file to optimize")

    args = parser.parse_args()

    if not args.command:
        parser.print_help()
        return

    analyzer = GrokCodeAnalyzer()
    generator = GrokCodeGenerator()

    if args.command == "analyze":
        filepath = Path(args.filepath)
        if not filepath.exists():
            print(f"❌ File not found: {filepath}")
            return

        analysis = analyzer.analyze_file(filepath)
        print("🔍 Grok-Code Analysis Results")
        print("=" * 50)
        print(f"File: {analysis['filepath']}")
        print(f"Lines: {analysis['lines']}")
        print(f"Classes: {', '.join(analysis['classes']) or 'None'}")
        print(f"Functions: {', '.join(analysis['functions']) or 'None'}")
        print(f"Invariant Usage: {analysis['invariant_usage'] or 'None'}")

        if analysis['issues']:
            print(f"Issues: {', '.join(analysis['issues'])}")

        if analysis['suggestions']:
            print("💡 Suggestions:")
            for suggestion in analysis['suggestions']:
                print(f"  • {suggestion}")

    elif args.command == "generate":
        code = generator.generate_theorem_implementation(args.theorem, args.description)
        print("🤖 Grok-Code Generated Implementation")
        print("=" * 50)
        print(code)

    elif args.command == "testgen":
        filepath = Path(args.filepath)
        if not filepath.exists():
            print(f"❌ File not found: {filepath}")
            return

        analysis = analyzer.analyze_file(filepath)
        test_template = analyzer.generate_test_template(analysis)
        print("🧪 Grok-Code Generated Test Template")
        print("=" * 50)
        print(test_template)

    elif args.command == "optimize":
        filepath = Path(args.filepath)
        if not filepath.exists():
            print(f"❌ File not found: {filepath}")
            return

        optimization = analyzer.optimize_code(filepath)
        print("⚡ Grok-Code Optimization Suggestions")
        print("=" * 50)
        print(f"File: {optimization['filepath']}")
        print(f"Estimated Improvement: {optimization['estimated_improvement']}")
        print()

        for category, suggestions in optimization['optimizations'].items():
            if suggestions:
                print(f"{category.title()}:")
                for suggestion in suggestions:
                    print(f"  • {suggestion}")
                print()

if __name__ == "__main__":
    main()
